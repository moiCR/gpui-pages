mod generate;
pub mod layout;
pub mod route;

pub use generate::{GenerateError, generate};

const VIEWS_DIR: &str = "src/pages";
const MODULES_FILE: &str = "src/pages_modules.rs";
const GENERATED_HEADER: &str = "// @generated by pages-codegen\n";

pub fn build() -> Result<(), Box<dyn std::error::Error>> {
    use std::{env, fs, io, path::PathBuf};
    println!("cargo:rerun-if-changed={VIEWS_DIR}");
    println!("cargo:rerun-if-changed={MODULES_FILE}");
    let crate_root =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("missing CARGO_MANIFEST_DIR")?);
    let out_dir = env::var_os("OUT_DIR").ok_or("missing OUT_DIR")?;
    let output = PathBuf::from(out_dir).join("pages.rs");
    let generated = generate::generate_tracking(&crate_root, |source| {
        println!("cargo:rerun-if-changed={}", source.display());
    })
    .map_err(|error| error.to_string())?;
    let modules = crate_root.join(MODULES_FILE);
    let contents = format!("{GENERATED_HEADER}{}", generated.modules);
    match fs::read_to_string(&modules) {
        Ok(existing) if existing == contents => {}
        Ok(existing) if !existing.starts_with(GENERATED_HEADER) => {
            return Err(format!(
                "{} already exists and is not managed by pages-codegen",
                modules.display()
            )
            .into());
        }
        Err(error) if error.kind() != io::ErrorKind::NotFound => return Err(error.into()),
        _ => fs::write(&modules, contents)
            .map_err(|error| format!("cannot write {}: {error}", modules.display()))?,
    }
    fs::write(&output, generated.registry)
        .map_err(|error| format!("cannot write {}: {error}", output.display()))?;
    Ok(())
}
